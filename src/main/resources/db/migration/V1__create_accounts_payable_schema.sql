-- Accounts payable schema. Works on PostgreSQL and on H2 in PostgreSQL mode.

CREATE TABLE suppliers (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    code        VARCHAR(20)  NOT NULL UNIQUE,
    name        VARCHAR(120) NOT NULL,
    email       VARCHAR(120),
    created_at  TIMESTAMP    NOT NULL
);

CREATE TABLE invoices (
    id              BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    supplier_id     BIGINT         NOT NULL REFERENCES suppliers (id),
    invoice_number  VARCHAR(40)    NOT NULL,
    po_number       VARCHAR(40),
    invoice_date    DATE           NOT NULL,
    due_date        DATE           NOT NULL,
    amount          NUMERIC(15, 2) NOT NULL CHECK (amount > 0),
    amount_paid     NUMERIC(15, 2) DEFAULT 0 NOT NULL,
    status          VARCHAR(20)    NOT NULL,
    captured_by     VARCHAR(60)    NOT NULL,
    approved_by     VARCHAR(60),
    created_at      TIMESTAMP      NOT NULL,
    -- A supplier cannot submit the same invoice number twice (duplicate payment control)
    CONSTRAINT uq_invoice_per_supplier UNIQUE (supplier_id, invoice_number),
    CONSTRAINT chk_paid_not_more_than_amount CHECK (amount_paid <= amount)
);

CREATE INDEX idx_invoices_status ON invoices (status);
CREATE INDEX idx_invoices_due_date ON invoices (due_date);

CREATE TABLE payments (
    id            BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    invoice_id    BIGINT         NOT NULL REFERENCES invoices (id),
    amount        NUMERIC(15, 2) NOT NULL CHECK (amount > 0),
    payment_date  DATE           NOT NULL,
    reference     VARCHAR(60)    NOT NULL,
    paid_by       VARCHAR(60)    NOT NULL,
    created_at    TIMESTAMP      NOT NULL
);

CREATE INDEX idx_payments_invoice ON payments (invoice_id);

CREATE TABLE audit_events (
    id           BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    actor        VARCHAR(60)  NOT NULL,
    action       VARCHAR(40)  NOT NULL,
    entity_type  VARCHAR(40)  NOT NULL,
    entity_id    BIGINT       NOT NULL,
    details      VARCHAR(500),
    occurred_at  TIMESTAMP    NOT NULL
);

CREATE INDEX idx_audit_entity ON audit_events (entity_type, entity_id);
